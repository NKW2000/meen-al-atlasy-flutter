اكتب لي بنك أسئلة للعبة "مين الأطليسي" (سؤال واحد وإله عدة أجوبة صحيحة، وكل جواب إله نقاط حسب شيوعه).

القواعد — التزم فيها حرفياً:
1. الناتج ملف JSON واحد فقط: مصفوفة من الأسئلة، بدون أي نص قبلها أو بعدها وبدون علامات markdown.
2. كل سؤال كائن فيه:
   - "id": نص فريد (q001، q002، …)
   - "text": نص السؤال باللهجة العامية، بيبلّش بـ "اذكر …"
   - "isreaded": false
   - "answers": مصفوفة فيها من ${QuestionBank.minAnswers} لـ ${QuestionBank.maxAnswers} أجوبة، كل جواب كائن فيه "text" (نص) و"points" (رقم صحيح أكبر من صفر)
3. كل الأجوبة لازم تكون صحيحة (مش جواب صح وباقي غلط)، وبديهية ومألوفة وبتخطر عالبال فوراً — لا أجوبة غريبة أو نادرة.
4. ما في جوابين بنفس المعنى جوّا نفس السؤال، وما في سؤالين بنفس المعنى بالبنك.
5. رتّب الأجوبة من الأعلى نقاط للأقل، ومجموع النقاط بكل سؤال ١٠٠ تقريباً.
6. أسئلة من الحياة اليومية ومعلومات عامة بسيطة (حيوانات، رياضة، أكل، ثقافة، تاريخ…)، وبدون أي محتوى مخالف للشريعة الإسلامية.
7. بدون حقل "category".

مثال على الشكل المطلوب:
[
  {
    "id": "q001",
    "text": "اذكر شي بيعمله الناس أول ما يصحوا من النوم",
    "isreaded": false,
    "answers": [
      {"text": "يشيّكوا الموبايل", "points": 40},
      {"text": "يشربوا قهوة", "points": 30},
      {"text": "يغسلوا وجّهم", "points": 20},
      {"text": "يصلّوا", "points": 10}
    ]
  }
]

اكتب لي $count سؤال بهالشكل.
''';
